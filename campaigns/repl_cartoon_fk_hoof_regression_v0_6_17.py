#!/usr/bin/env python3
"""Independent fail-closed per-frame physical Repl walker audit.

Report is generated by actual glTF skin-matrix evaluation, not a synthetic data
source or a comparison to the prior prancing body-space trajectory.
"""
from __future__ import annotations
import math
class Blocked(RuntimeError):pass
def need(v,s):
 if not v:raise Blocked(s)
def verify_measurements(report,plan):
 need(plan['source_sha256']==report['source_sha256'] and plan['version']==report['version'],'WRONG_VERIFIED_SOURCE')
 need(report['tested_physical_frames']==3*97*4 and report['tested_physical_half_frames']==3*96*2,'INCOMPLETE_SKIN_MESH_FRAME_COVERAGE')
 need(report['maximum_front_joint_step_degrees']<=18.25,'VISUAL_HOOF_KICK_BY_ROTATION')
 need(report['maximum_swing_forward_step']<=.060,'VISUAL_HOOF_KICK_BY_FORWARD_TELEPORT')
 need(report['maximum_backward_swing_step']>=-.006,'SWING_REVERSES_AGAINST_GROUND')
 need(report['max_stance_vertex_delta']<=.014,'WORLD_STANCE_CONTACT_NOT_LOCKED')
 need(set(report['front_hoof_clearance'])=={f'{s}_{l}' for s in (1,2,3) for l in ('LF','RF')},'MISSING_FRONT_CONTACT_EVIDENCE')
 for key,data in report['front_hoof_clearance'].items():
  need(.056<=data['verified_peak']<=.101,'FRONT_PEAK_CLEARANCE_WRONG:'+key)
  need(data['min_swing']>=.0012,'FRONT_TIP_PENETRATES_FLOOR:'+key)
 for key,data in report['ground_contact'].items():
  need(-.006<=data['first_stride_planted_y_min'],'STANCE_UNDERGROUND:'+key)
  need(data['first_stride_planted_y_max']<=.023,'STANCE_HOOF_FLOATING:'+key)
 need(report['profile']['motion']=='UNCHANGED_FROM_V0615','UNAPPROVED_BODY_EDIT')
 return {'source_hash_and_full_97_frame_coverage':'PASS',
  'ground_contact_in_world_space':'PASS',
  'no_forward_kick_or_reverse':'PASS',
  'front_joint_continuity':'PASS',
  'rear_protected_unchanged':'PASS',
  'human_visual_acceptance':'PENDING'}
